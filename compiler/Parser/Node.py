from dataclasses import dataclass
from abc import *
from typing import List, Dict

from Scanner.Kind import Kind

@dataclass
class Statement(metaclass = ABCMeta):
    def __nonzero__(self) -> bool:
        return any(vars(self).values())

@dataclass
class Expression(metaclass = ABCMeta):
    def __nonzero__(self) -> bool:
        return any(vars(self).values())

@dataclass
class Function(Statement):
    name: str = ...
    parameters: List[str] = ...
    block: List[Statement] = ...

@dataclass
class Program:
    functions: List[Function] = ...

@dataclass
class Return(Statement):
    expression: Expression = ...

@dataclass
class Variable(Statement):
    name: str = ...
    expression: Expression = ...

@dataclass
class For(Statement):
    variable: Variable = ...
    condition: Expression = ...
    expression: Expression = ...
    block: List[Statement] = ...

@dataclass
class Break(Statement): ...

@dataclass
class Continue(Statement): ...
    
@dataclass
class If(Statement):
    conditions: List[Expression] = ...
    blocks: List[List[Statement]] = ...
    elseBlock: List[Statement] = ...
    
@dataclass
class Print(Statement):
    lineFeed: bool = False
    arguments: List[Expression] = ...

@dataclass
class ExpressionStatement(Statement):
    expression: Expression = ...
    
@dataclass
class Or(Expression):
    left: Expression = ...
    right: Expression = ...
    
@dataclass
class And(Expression):
    left: Expression = ...
    right: Expression = ...
    
@dataclass
class Relational(Expression):
    kind: Kind = ...
    left: Expression = ...
    right: Expression = ...
    
@dataclass
class Arithmetic(Expression):
    kind: Kind = ...
    left: Expression = ...
    right: Expression = ...

@dataclass
class Unary(Expression):
    kind: Kind = ...
    sub: Expression = ...
    
@dataclass
class Call(Expression):
    sub: Expression = ...
    arguments: List[Expression] = ...
    
@dataclass
class GetElement(Expression):
    sub: Expression = ...
    index: Expression = ...
    
@dataclass
class SetElement(Expression):
    sub: Expression = ...
    index: Expression = ...
    value: Expression = ...

@dataclass
class GetVariable(Expression):
    name: str = ...
    
@dataclass
class SetVariable(Expression):
    name: str = ...
    value: Expression = ...

@dataclass
class NullLiteral(Expression): ...

@dataclass
class BooleanLiteral(Expression):
    value: bool = False

@dataclass
class NumberLiteral(Expression):
    value: float = 0.0

@dataclass
class StringLiteral(Expression):
    value: str = ""

@dataclass
class ArrayLiteral(Expression):
    values: List[Expression] = ...

@dataclass
class MapLiteral(Expression):
    values: Dict[NullLiteral | BooleanLiteral | NumberLiteral | StringLiteral, Expression]